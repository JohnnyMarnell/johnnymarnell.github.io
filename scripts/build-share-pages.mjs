/*
 * Generates share/<slug>.md — one page per gallery item — plus the downsized
 * preview JPEGs the photos need. Run `just share`.
 *
 * Why these pages exist at all. A link preview in WhatsApp, iMessage, Slack or
 * Discord is built by a crawler that fetches the URL and reads `og:` meta tags
 * out of the HTML. It does not run JavaScript, and GitHub Pages serves
 * byte-identical HTML for /led/?m=anything — so every ?m= link would preview
 * as the same page no matter which item it pointed at. A per-item preview
 * needs a per-item *path*, and on a plugin-less static host that means a real
 * file per item, committed. This writes them.
 *
 * Each page renders the whole gallery (the same _includes/led-body.md as
 * /led/), so a human who opens the link gets the real page — and gallery.js,
 * seeing its own slug in the path, scrolls down and opens that item. Only the
 * front matter differs, which is what jekyll-seo-tag turns into og: tags.
 *
 * Preview images:
 *   videos  hotlink YouTube's own poster (i.ytimg.com, 45-100 KB, 1280x720) —
 *           literally the image YouTube's own links preview with.
 *   photos  cannot be used as shot: the originals here are 0.8-2.8 MB at
 *           4032px, and crawlers skip images that big. So each gets a ~1200px
 *           copy in assets/share/, generated here and committed.
 *
 * `--check` regenerates into memory and diffs against what is on disk, without
 * writing: that is what tests/led-share.spec.js runs, so a gallery item added
 * without `just share` fails the suite instead of silently shipping a page
 * whose links preview as the wrong thing.
 */
import { readFile, writeFile, readdir, mkdir, unlink, stat } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const REPO = new URL("..", import.meta.url).pathname;
const SHARE_DIR = join(REPO, "share");
const PREVIEW_DIR = join(REPO, "assets/share");
const PREVIEW_WIDTH = 1200;

const check = process.argv.includes("--check");
const force = process.argv.includes("--force");

/* ------------------------------------------------------------------ data --- */

// Ruby rather than a YAML package: Jekyll already makes Ruby a hard dependency
// of this repo, and node ships no YAML parser.
function yaml(path) {
  return JSON.parse(
    execFileSync("ruby", ["-ryaml", "-rjson", "-e", "puts YAML.load_file(ARGV[0]).to_json", path], {
      encoding: "utf8",
    }),
  );
}

const led = yaml(join(REPO, "_data/led.yml"));
const media = yaml(join(REPO, "_data/media.yml"));

// Must match the slug the includes stamp onto each tile, or a share page and
// the gallery would disagree about what /led/<slug>/ means.
const imageSlug = (path) => path.split("/").pop().split(".")[0].toLowerCase().replace(/_/g, "-");

/* -------------------------------------------------------------- previews --- */

const has = (cmd) => {
  try {
    execFileSync("/bin/sh", ["-c", `command -v ${cmd}`], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
};

const resizer = has("ffmpeg") ? "ffmpeg" : has("sips") ? "sips" : null;

async function makePreview(src, dest) {
  if (!resizer) {
    throw new Error(
      `need ffmpeg (or sips on macOS) to build ${dest}.\n` +
        "  brew install ffmpeg   /   apt install ffmpeg",
    );
  }
  await mkdir(PREVIEW_DIR, { recursive: true });
  if (resizer === "ffmpeg") {
    execFileSync(
      "ffmpeg",
      ["-y", "-loglevel", "error", "-i", src,
       "-vf", `scale=${PREVIEW_WIDTH}:-2:flags=lanczos`,
       "-q:v", "4", "-map_metadata", "-1", dest],
      { stdio: "inherit" },
    );
  } else {
    execFileSync("sips", ["-Z", String(PREVIEW_WIDTH), src, "--out", dest], { stdio: "ignore" });
  }
}

/* ----------------------------------------------------------------- pages --- */

// JSON strings are valid YAML scalars, which saves inventing quoting rules for
// captions that contain colons, dashes and apostrophes.
const q = (v) => JSON.stringify(String(v));

function stub({ slug, title, description, image }) {
  return `---
# Generated by \`just share\` (scripts/build-share-pages.mjs). Do not edit by hand.
# One page per item in _data/led.yml, so a pasted link previews *that* item:
# a crawler reads these og: tags and never runs JS. Add an item -> run it again.
layout: gallery
permalink: /led/${slug}/
title: ${q(title)}
description: ${q(description)}
image:
  path: ${q(image.path)}
  width: ${image.width}
  height: ${image.height}
  alt: ${q(title)}
---

{% include led-body.md %}
`;
}

const description = led.share.description.trim().replace(/\s+/g, " ");
const wanted = new Map(); // slug -> file contents
const previews = []; // [sourcePath, destPath, slug]

for (const item of led.items) {
  if (item.video) {
    const known = media.videos?.[item.video];
    if (!known) throw new Error(`${item.video} is not in _data/media.yml — run \`just media\``);
    if (!known.poster) throw new Error(`${item.video} has no poster in _data/media.yml — run \`just media\``);
    wanted.set(item.video, stub({
      slug: item.video,
      title: item.alt,
      description,
      /*
       * YouTube's own poster — a 1280x720 composite whatever the video's
       * shape, so a portrait clip previews exactly the way a youtube.com link
       * for it does. Which file is real was settled by `just media`:
       * maxresdefault is simply missing for some uploads, and an og:image that
       * 404s renders as no preview.
       */
      image: {
        path: `https://i.ytimg.com/vi/${item.video}/${known.poster}`,
        width: known.poster_width,
        height: known.poster_height,
      },
    }));
  } else {
    const known = media.images?.[item.image];
    if (!known) throw new Error(`${item.image} is not in _data/media.yml — run \`just media\``);
    const slug = imageSlug(item.image);
    const scale = Math.min(1, PREVIEW_WIDTH / known.width);
    const width = Math.round(known.width * scale);
    // -2 in the ffmpeg filter rounds height to an even number; match it, or
    // og:image:height would be a pixel off what the file actually is.
    const height = Math.round((known.height * scale) / 2) * 2;
    previews.push([join(REPO, item.image.replace(/^\//, "")), join(PREVIEW_DIR, `${slug}.jpg`), slug]);
    wanted.set(slug, stub({
      slug,
      title: item.alt,
      description,
      image: { path: `/assets/share/${slug}.jpg`, width, height },
    }));
  }
}

/* ---------------------------------------------------------------- write --- */

const existing = new Map();
for (const name of (await readdir(SHARE_DIR).catch(() => [])).sort()) {
  if (!name.endsWith(".md")) continue;
  existing.set(name.slice(0, -3), await readFile(join(SHARE_DIR, name), "utf8"));
}

const stale = [...existing.keys()].filter((s) => !wanted.has(s));
const changed = [...wanted].filter(([s, body]) => existing.get(s) !== body).map(([s]) => s);
const missingPreviews = [];
for (const [src, dest, slug] of previews) {
  const info = await stat(dest).catch(() => null);
  if (!info || force) missingPreviews.push([src, dest, slug]);
}

if (check) {
  const problems = [
    ...changed.map((s) => `share/${s}.md is stale or missing`),
    ...stale.map((s) => `share/${s}.md is no longer in _data/led.yml`),
    ...missingPreviews.map(([, , s]) => `assets/share/${s}.jpg is missing`),
  ];
  if (problems.length) {
    console.error("share pages are out of date — run `just share`:");
    for (const p of problems) console.error(`  ${p}`);
    process.exit(1);
  }
  console.log(`share pages up to date — ${wanted.size} items`);
  process.exit(0);
}

await mkdir(SHARE_DIR, { recursive: true });
for (const [slug, body] of wanted) {
  if (existing.get(slug) === body) continue;
  await writeFile(join(SHARE_DIR, `${slug}.md`), body);
  console.log(`  share/${slug}.md`);
}
for (const slug of stale) {
  await unlink(join(SHARE_DIR, `${slug}.md`));
  console.log(`  removed share/${slug}.md`);
}
for (const [src, dest, slug] of missingPreviews) {
  await makePreview(src, dest);
  const { size } = await stat(dest);
  console.log(`  assets/share/${slug}.jpg  ${(size / 1024).toFixed(0)} KB`);
}

console.log(
  `\n${wanted.size} share pages, ${previews.length} photo previews` +
    `${changed.length || stale.length || missingPreviews.length ? "" : " (nothing to do)"}`,
);
